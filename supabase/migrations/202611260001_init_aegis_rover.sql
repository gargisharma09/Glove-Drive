-- 1. Rover Telemetry Logs (time-series snapshots from Simulation or ESP32 WebSocket)
CREATE TABLE IF NOT EXISTS public.telemetry_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  device_id TEXT NOT NULL DEFAULT 'GLOVEDRIVE-ESP32-01',
  mode TEXT NOT NULL DEFAULT 'SIMULATION',
  command TEXT NOT NULL DEFAULT 'IDLE',
  control_lock TEXT NOT NULL DEFAULT 'MANUAL_SIM_OVERRIDE',
  direction TEXT NOT NULL DEFAULT 'IDLE',
  velocity_cm_s INTEGER NOT NULL DEFAULT 0,
  steering_deg REAL NOT NULL DEFAULT 0,
  pwm_left SMALLINT NOT NULL DEFAULT 0,
  pwm_right SMALLINT NOT NULL DEFAULT 0,
  rpm_left INTEGER NOT NULL DEFAULT 0,
  rpm_right INTEGER NOT NULL DEFAULT 0,
  battery_v REAL NOT NULL DEFAULT 12.42,
  rssi_dbm INTEGER NOT NULL DEFAULT -54,
  front_dist_cm INTEGER NOT NULL DEFAULT 285,
  rear_dist_cm INTEGER NOT NULL DEFAULT 340,
  temp_c REAL NOT NULL DEFAULT 26.4,
  humidity_pct REAL NOT NULL DEFAULT 48.2,
  gas_raw INTEGER NOT NULL DEFAULT 215,
  hazard_score SMALLINT NOT NULL DEFAULT 28,
  person_detected BOOLEAN NOT NULL DEFAULT FALSE,
  emergency_stop BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_telemetry_logs_created_at
  ON public.telemetry_logs (created_at DESC);

-- 2. Safety & Validator Alerts (E-Stop, Voice Stop Shortcut, Hazard/Gas Thresholds)
CREATE TABLE IF NOT EXISTS public.safety_alerts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  device_id TEXT NOT NULL DEFAULT 'GLOVEDRIVE-ESP32-01',
  source TEXT NOT NULL,
  severity TEXT NOT NULL DEFAULT 'ELEVATED',
  message TEXT NOT NULL,
  command TEXT,
  hazard_score SMALLINT,
  emergency_stop BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_safety_alerts_created_at
  ON public.safety_alerts (created_at DESC);

-- 3. Multi-Node Device Health & Link Status
CREATE TABLE IF NOT EXISTS public.device_nodes (
  node_id TEXT PRIMARY KEY,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  title TEXT NOT NULL,
  proto TEXT NOT NULL,
  ip TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'NOMINAL',
  latency_ms INTEGER NOT NULL DEFAULT 0,
  packet_rate INTEGER NOT NULL DEFAULT 0,
  signal TEXT
);

-- 4. ESP32-CAM Vision & Hazard Snapshots
CREATE TABLE IF NOT EXISTS public.vision_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  device_id TEXT NOT NULL DEFAULT 'GLOVEDRIVE-ESP32-01',
  fps SMALLINT NOT NULL DEFAULT 24,
  person_detected BOOLEAN NOT NULL DEFAULT FALSE,
  confidence REAL NOT NULL DEFAULT 0,
  hazard_score SMALLINT NOT NULL DEFAULT 0,
  frame_url TEXT
);

CREATE INDEX IF NOT EXISTS idx_vision_snapshots_created_at
  ON public.vision_snapshots (created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.telemetry_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.safety_alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_nodes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vision_snapshots ENABLE ROW LEVEL SECURITY;

